#!/usr/bin/env python3
"""cad/import.py — drop any robot GLB into the sim.

Reads the GLB's real bounds, writes the model into
web/public/robot-assets/, and emits an archetype TOML with measured
half_extents + mass estimate. Joints/mechanisms are hand-declared on top.

Usage:  python3 cad/import.py <model.glb> <robot-name> [mass_kg]
"""
import json, struct, sys, shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSETS = REPO / "web/public/robot-assets"

def glb_bounds(path):
    d = open(path, 'rb').read()
    ln = struct.unpack('<I', d[12:16])[0]
    j = json.loads(d[20:20+ln])
    gmin = [1e9]*3; gmax = [-1e9]*3
    for m in j.get('meshes', []):
        for p in m['primitives']:
            acc = j['accessors'][p['attributes']['POSITION']]
            mn, mx = acc.get('min'), acc.get('max')
            if mn and mx:
                for k in range(3):
                    gmin[k] = min(gmin[k], mn[k]); gmax[k] = max(gmax[k], mx[k])
    return gmin, gmax

def main():
    src, name = sys.argv[1], sys.argv[2]
    mass = float(sys.argv[3]) if len(sys.argv) > 3 else 60.0
    gmin, gmax = glb_bounds(src)
    dims = [round(gmax[k]-gmin[k], 3) for k in range(3)]
    half = [round(dims[k]/2, 3) for k in range(3)]
    center = [round((gmin[k]+gmax[k])/2, 3) for k in range(3)]

    dst = ASSETS / f"{name}.glb"
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(src, dst)

    # FRC rules: chassis <= 0.915 m per side — clamp half extents there
    # so the collider doesn't overstate the model
    clamp = [min(h, 0.4575) for h in half]

    toml = f'''name = "{name}"
# generated by cad/import.py — bounds from the GLB
mass = {mass}
half_extents = {clamp}
max_force = 1200.0
drivetrain = "swerve"

# model bounds: min={gmin} max={gmax} (raw, meters)
# dims {dims}m — scale centers on the ground plane
[model]
url = "/robot-assets/{name}.glb"
scale = 0.5
offset = [-{center[0]:.3f}, 0.0, -{center[2]:.3f}]
rotation_deg = [0.0, 0.0, 0.0]

[sensors]
preset = "competition"
'''
    out = REPO / "archetypes" / f"{name}.toml"
    out.write_text(toml)
    print(f"installed {dst}")
    print(f"archetype {out}  dims={dims}m half={clamp}")

if __name__ == "__main__":
    main()
